# Cache: raw name -> canonical key (normalized alias-resolved string)
_canonical_cache = {}


def normalize_name(name: str) -> str:
    """Lowercase + strip everything that isn't a letter or digit."""
    return "".join(ch for ch in name.lower() if ch.isalnum())


def _canonical_key(raw_name: str) -> str:
    """
    Resolve a raw category name to its canonical key:
      normalize -> lookup alias table (on normalized keys) -> canonical.
    """
    if raw_name in _canonical_cache:
        return _canonical_cache[raw_name]

    norm = normalize_name(raw_name)
    key = norm
    for alias_raw, canonical in ALIASES.items():
        if normalize_name(alias_raw) == norm:
            key = normalize_name(canonical)
            break
    _canonical_cache[raw_name] = key
    return key


def canonicalize(name: str) -> str:
    """Canonical Sketchy-style name for any dataset category name."""
    return _canonical_key(name)


def build_canonical_map(canonical_names):
    """
    Build {normalized canonical key: canonical name} for matching.
    canonical_names: iterable of canonical category names (from Sketchy).
    """
    return {normalize_name(n): n for n in canonical_names}


def map_to_canonical(raw_name: str, canon_key_to_name: dict):
    """
    Map a raw category name to its canonical partner.

    Returns canonical name (str) or None if no match found.
    """
    return canon_key_to_name.get(_canonical_key(raw_name))


